    void mostrarDatosFormulario() {

    int fila = jTable1.getSelectedRow();

    if (fila == -1) return;

    txtFReserva.setText(
        jTable1.getValueAt(fila, 1).toString()
    );

    txtFEntrada.setText(
        jTable1.getValueAt(fila, 2).toString()
    );

    txtFSalida.setText(
        jTable1.getValueAt(fila, 3).toString()
    );

    txtEstado.setText(
        jTable1.getValueAt(fila, 4).toString()
    );

    txtCliente.setText(
        jTable1.getValueAt(fila, 5).toString()
    );

    txtHabitacion.setText(
        jTable1.getValueAt(fila, 6).toString()
    );
}

    void inicializarTabla() {
        
        modelo.addColumn("ID");
        modelo.addColumn("Fecha Reserva");
        modelo.addColumn("Fecha Entrada");
        modelo.addColumn("Fecha Salida");
        modelo.addColumn("Estado");
        modelo.addColumn("Cliente");
        modelo.addColumn("Habitación");

        
        jTable1.setModel(modelo);
}
    void cargarDatos() {
        modelo.setRowCount(0);
        for (Reserva r : dao.listar()) {

            modelo.addRow(new Object[]{
            r.getId_reserva(),
            r.getFecha_reserva(),
            r.getFecha_entrada(),
            r.getFecha_salida(),
            r.getEstado(),
            r.getCliente().getId_cliente(),
            r.getHabitacion().getId_habitacion()
        });
    }
}
    void limpiarCampos() {

    txtCliente.setText("");
    txtFReserva.setText("");
    txtFEntrada.setText("");
    txtFSalida.setText("");
    txtHabitacion.setText("");
    txtEstado.setText("");
}

