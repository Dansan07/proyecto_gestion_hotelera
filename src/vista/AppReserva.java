    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {

        java.util.Date fechaReserva =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFReserva.getText());

        java.util.Date fechaEntrada =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFEntrada.getText());

        java.util.Date fechaSalida =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFSalida.getText());

        Cliente c = new Cliente();
        c.setId_cliente(Integer.parseInt(txtCliente.getText()));

        Habitacion h = new Habitacion();
        h.setId_habitacion(Integer.parseInt(txtHabitacion.getText()));

        Reserva r = new Reserva(
            0,
            fechaReserva,
            fechaEntrada,
            fechaSalida,
            txtEstado.getText(),
            c,
            h
        );

        dao.insertar(r);

        cargarDatos();

        limpiarCampos();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Error al guardar"
        );
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        int fila = jTable1.getSelectedRow();

    if (fila == -1) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Selecciona una reserva"
        );

        return;
    }

    try {

        int id = Integer.parseInt(
            jTable1.getValueAt(fila, 0).toString()
        );

        java.util.Date fechaReserva =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFReserva.getText());

        java.util.Date fechaEntrada =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFEntrada.getText());

        java.util.Date fechaSalida =
            new SimpleDateFormat("yyyy-MM-dd")
            .parse(txtFSalida.getText());

        Cliente c = new Cliente();
        c.setId_cliente(
            Integer.parseInt(txtCliente.getText())
        );

        Habitacion h = new Habitacion();
        h.setId_habitacion(
            Integer.parseInt(txtHabitacion.getText())
        );

        Reserva r = new Reserva(
            id,
            fechaReserva,
            fechaEntrada,
            fechaSalida,
            txtEstado.getText(),
            c,
            h
        );

        dao.actualizar(r);

        cargarDatos();

        limpiarCampos();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Error al actualizar"
        );
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = jTable1.getSelectedRow();

    if (fila == -1) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Selecciona una reserva"
        );

        return;
    }

    try {

        int id = Integer.parseInt(
            jTable1.getValueAt(fila, 0).toString()
        );

        dao.eliminar(id);

        cargarDatos();

        limpiarCampos();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Error al eliminar"
        );
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

