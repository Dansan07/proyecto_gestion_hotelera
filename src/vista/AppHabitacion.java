    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {

        TipoHabitacion t = new TipoHabitacion();

        t.setId_tipo(
            Integer.parseInt(txtTipoHab.getText())
        );

        Habitacion h = new Habitacion(0,txtNumeroHabitacion.getText(),chkDisponible.isSelected(),t);

        dao.insertar(h);

        cargarDatos();
        limpiarCampos();
        
        JOptionPane.showMessageDialog(null,"Habitación registrada correctamente");

    } catch(Exception e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(
            null,
            e.getMessage()
    );
}
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        int fila = jTable4.getSelectedRow();

    if(fila == -1){

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Seleccione una habitación"
        );

        return;
    }

    try {

        int id = Integer.parseInt(
            jTable4.getValueAt(fila,0).toString()
        );

        TipoHabitacion t = new TipoHabitacion();

        t.setId_tipo(
            Integer.parseInt(txtTipoHab.getText())
        );

        Habitacion h = new Habitacion(
    id,
    txtNumeroHabitacion.getText(),
    chkDisponible.isSelected(),
    t
);

        dao.actualizar(h);

        cargarDatos();

        limpiarCampos();
        
        JOptionPane.showMessageDialog(null,"Habitación actualizada correctamente");

    } catch(Exception e) {

        e.printStackTrace();

            JOptionPane.showMessageDialog(
            null,
        e.getMessage()
    );
}
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = jTable4.getSelectedRow();

    if(fila == -1){

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Seleccione una habitación"
        );

        return;
    }

    try {

        int id = Integer.parseInt(
            jTable4.getValueAt(fila,0).toString()
        );

        dao.eliminar(id);

        cargarDatos();

        limpiarCampos();
        
        JOptionPane.showMessageDialog(null,"Habitación eliminada correctamente");

    } catch(Exception e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(
            null,
            e.getMessage()
    );
}
    }//GEN-LAST:event_btnEliminarActionPerformed

