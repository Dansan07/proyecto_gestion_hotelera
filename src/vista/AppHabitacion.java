    void inicializarTabla() {

    modelo.addColumn("ID");
    modelo.addColumn("Número");
    modelo.addColumn("Disponible");
    modelo.addColumn("Tipo Habitación");

    jTable4.setModel(modelo);
}
    
    void cargarDatos() {

    modelo.setRowCount(0);

    for(Habitacion h : dao.listar()) {

        modelo.addRow(new Object[]{

            h.getId_habitacion(),
            h.getNumero_habitacion(),
            h.isDisponible(),
            h.getTipoHabitacion().getNombre_tipo()

        });
    }
}
    
    void limpiarCampos() {

    txtNumeroHabitacion.setText("");
    chkDisponible.setSelected(false);
    txtTipoHab.setText("");
}
    
    void mostrarDatosFormulario() {

    int fila = jTable4.getSelectedRow();

    if(fila == -1) return;

    txtNumeroHabitacion.setText(
        jTable4.getValueAt(fila,1).toString()
    );

    chkDisponible.setSelected(
    Boolean.parseBoolean(
        jTable4.getValueAt(fila,2).toString()
    )
);

    txtTipoHab.setText(
        jTable4.getValueAt(fila,3).toString()
    );
}

